// Kéo OpenAPI spec từ backend đang chạy, lưu api/openapi.json (key đã sort để diff ổn định)
// và sinh type TS vào src/lib/api/schema.gen.ts.
// Dùng: pnpm api:sync   (đổi nguồn: API_DOCS_URL=http://host:9100/api/v3/api-docs pnpm api:sync)
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const url = process.env.API_DOCS_URL ?? "http://localhost:9100/api/v3/api-docs";
const specPath = resolve(root, "api/openapi.json");
const typesPath = resolve(root, "src/lib/api/schema.gen.ts");

const sortKeys = (value) => {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sortKeys(value[k])])
    );
  }
  return value;
};

let res;
try {
  res = await fetch(url).catch((err) => {
    // Node resolve "localhost" thành ::1 trước, còn Spring Boot thường chỉ nghe IPv4.
    if (err.cause?.code !== "ECONNREFUSED" || new URL(url).hostname !== "localhost") throw err;
    return fetch(url.replace("//localhost", "//127.0.0.1"));
  });
} catch (err) {
  console.error(`api:sync: không gọi được ${url} — backend đã chạy chưa? (${err.cause?.code ?? err.message})`);
  process.exit(1);
}
if (!res.ok) {
  console.error(`api:sync: ${url} trả về HTTP ${res.status}`);
  process.exit(1);
}

const spec = sortKeys(await res.json());
await mkdir(dirname(specPath), { recursive: true });
await writeFile(specPath, JSON.stringify(spec, null, 2) + "\n");

const ast = await openapiTS(spec);
const header = "// GENERATED by `pnpm api:sync` from the backend OpenAPI spec — do not edit.\n\n";
await writeFile(typesPath, header + astToString(ast));

const ops = Object.values(spec.paths ?? {}).reduce((n, item) => n + Object.keys(item).length, 0);
const schemas = Object.keys(spec.components?.schemas ?? {}).length;
console.log(`api:sync: ${ops} operations, ${schemas} schemas -> api/openapi.json, src/lib/api/schema.gen.ts`);
